def count_words(text: str) -> int:
    """
    Подсчитывает количество слов в строке text.
    Разделителем считается любой пробельный символ (пробел, табуляция, перевод строки).
    """
    # split() без аргументов разделяет по любым пробельным символам,
    # автоматически обрабатывая множественные пробелы.
    return len(text.split())
